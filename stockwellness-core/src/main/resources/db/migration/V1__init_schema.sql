CREATE TABLE stock_price_eod (
    stock_id bigint NOT NULL REFERENCES stock(id),
    trade_date date NOT NULL,
    quote_scope varchar(10) NOT NULL CHECK (quote_scope IN ('KRX','NXT','UNIFIED','LOCAL')),
    open_price numeric(19,4) CHECK (open_price >= 0),
    high_price numeric(19,4) CHECK (high_price >= 0),
    low_price numeric(19,4) CHECK (low_price >= 0),
    close_price numeric(19,4) CHECK (close_price >= 0),
    previous_close_price numeric(19,4) CHECK (previous_close_price >= 0),
    volume bigint CHECK (volume >= 0),
    trading_amount numeric(25,2) CHECK (trading_amount >= 0),
    no_trade boolean,
    source_api varchar(50) NOT NULL,
    data_status varchar(20) NOT NULL CHECK (data_status IN ('PROVISIONAL','FINAL','INCOMPLETE')),
    collected_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    corrected_at timestamptz,
    data_revision integer NOT NULL DEFAULT 1 CHECK (data_revision > 0),
    PRIMARY KEY (stock_id, trade_date, quote_scope),
    CHECK (data_status <> 'FINAL' OR close_price IS NOT NULL),
    CHECK (high_price IS NULL OR low_price IS NULL OR high_price >= low_price)
);
CREATE INDEX idx_stock_price_eod_date ON stock_price_eod(trade_date, quote_scope, stock_id);
