-- Actual accounts are independent of simulation portfolios. No conversion or deletion cascade.
create table actual_account (
    id bigint generated by default as identity primary key check (id between 1 and 9007199254740991),
    member_id bigint not null references member(id),
    name text not null check (char_length(name) between 1 and 50),
    broker_label text check (broker_label is null or char_length(broker_label) between 1 and 100),
    base_currency varchar(3) not null check (base_currency = 'KRW'),
    account_version bigint not null default 0 check (account_version between 0 and 9007199254740991),
    ledger_version bigint not null default 0 check (ledger_version between 0 and 9007199254740991),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);
create index idx_actual_account_owner on actual_account(member_id, id);

-- Successful receipts have no independent short TTL. Their lifetime follows the account/audit retention policy.
-- account_scope=0 is the member's CREATE_ACCOUNT namespace; rename uses the owned account ID.
create table actual_mutation_receipt (
    id bigint generated by default as identity primary key,
    member_id bigint not null references member(id),
    account_scope bigint not null check (account_scope between 0 and 9007199254740991),
    response_account_id bigint not null references actual_account(id),
    operation varchar(32) not null check (operation in ('CREATE_ACCOUNT','RENAME_ACCOUNT')),
    request_key varchar(64) not null check (request_key ~ '^[A-Za-z0-9_-]{16,64}$'),
    request_fingerprint varchar(64) not null check (request_fingerprint ~ '^[0-9a-f]{64}$'),
    response_body text not null,
    created_at timestamp with time zone not null,
    constraint uq_actual_receipt_scope unique (member_id, account_scope, operation, request_key),
    constraint ck_actual_receipt_target check (
        (operation = 'CREATE_ACCOUNT' and account_scope = 0) or
        (operation = 'RENAME_ACCOUNT' and account_scope = response_account_id))
);
