CREATE TABLE index_series (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    index_id bigint NOT NULL REFERENCES market_index(id),
    provider varchar(50) NOT NULL,
    provider_namespace varchar(80) NOT NULL,
    provider_series_code varchar(100) NOT NULL,
    calendar_market_code varchar(20) NOT NULL REFERENCES market(code),
    return_basis varchar(20) NOT NULL CHECK (return_basis IN ('PRICE','TOTAL_RETURN')),
    dividend_basis varchar(10) NOT NULL CHECK (dividend_basis IN ('NONE','GROSS','NET')),
    currency char(3) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    is_canonical boolean NOT NULL DEFAULT false,
    UNIQUE(provider,provider_namespace,provider_series_code,return_basis,dividend_basis,currency),
    CHECK ((return_basis='PRICE' AND dividend_basis='NONE') OR
           (return_basis='TOTAL_RETURN' AND dividend_basis IN ('GROSS','NET')))
);
CREATE UNIQUE INDEX uq_legacy_index_series_canonical
    ON index_series(index_id,return_basis,dividend_basis,currency)
    WHERE is_active AND is_canonical;

ALTER TABLE index_daily ADD CONSTRAINT fk_legacy_index_daily_series
    FOREIGN KEY (series_id) REFERENCES index_series(id);
CREATE UNIQUE INDEX uq_legacy_index_daily_series_date
    ON index_daily(series_id,trade_date) WHERE series_id IS NOT NULL;
